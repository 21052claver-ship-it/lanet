CREATE TABLE roulette_tickets (
 id TEXT PRIMARY KEY,
 user_id TEXT NOT NULL REFERENCES users(id),
 request_id TEXT NOT NULL,
 bets TEXT NOT NULL CHECK(json_valid(bets) AND json_type(bets)='array' AND json_array_length(bets) BETWEEN 1 AND 157),
 stake INTEGER NOT NULL CHECK(typeof(stake)='integer' AND stake BETWEEN 1 AND 1000),
 result INTEGER NOT NULL CHECK(typeof(result)='integer' AND result BETWEEN 0 AND 36),
 payout INTEGER NOT NULL CHECK(typeof(payout)='integer' AND payout BETWEEN 0 AND 36000),
 day TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT(strftime('%Y-%m-%dT%H:%M:%fZ','now')),
 UNIQUE(user_id,request_id)
);
CREATE INDEX roulette_tickets_user ON roulette_tickets(user_id,created_at);
CREATE TRIGGER roulette_ticket_guard BEFORE INSERT ON roulette_tickets BEGIN
 SELECT (CASE WHEN EXISTS(SELECT 1 FROM roulette_spins WHERE user_id=NEW.user_id AND request_id=NEW.request_id) THEN RAISE(ABORT,'roulette_request_conflict') END);
 SELECT (CASE WHEN EXISTS(
 SELECT 1 FROM json_each(NEW.bets) b LEFT JOIN roulette_positions p ON p.id=json_extract(b.value,'$.id')
 WHERE b.type!='object' OR p.id IS NULL OR json_type(b.value,'$.id') IS NOT 'text'
 OR json_type(b.value,'$.stake') IS NOT 'integer' OR json_extract(b.value,'$.stake') NOT BETWEEN 1 AND 1000
 OR (SELECT COUNT(*) FROM json_each(b.value))!=2
 OR EXISTS(SELECT 1 FROM json_each(b.value) WHERE key NOT IN('id','stake'))
 ) OR (SELECT COUNT(DISTINCT json_extract(value,'$.id')) FROM json_each(NEW.bets))!=json_array_length(NEW.bets)
 OR NEW.stake!=(SELECT SUM(json_extract(value,'$.stake')) FROM json_each(NEW.bets))
 OR NEW.payout!=(SELECT COALESCE(SUM(json_extract(b.value,'$.stake')*p.multiplier),0)
 FROM json_each(NEW.bets) b JOIN roulette_positions p ON p.id=json_extract(b.value,'$.id')
 WHERE EXISTS(SELECT 1 FROM json_each(p.numbers) WHERE value=NEW.result))
 THEN RAISE(ABORT,'roulette_invalid_ticket') END);
END;
CREATE TRIGGER roulette_legacy_request_guard BEFORE INSERT ON roulette_spins BEGIN
 SELECT (CASE WHEN EXISTS(SELECT 1 FROM roulette_tickets WHERE user_id=NEW.user_id AND request_id=NEW.request_id) THEN RAISE(ABORT,'roulette_request_conflict') END);
END;
CREATE TRIGGER roulette_ticket_settlement AFTER INSERT ON roulette_tickets BEGIN
 INSERT INTO ledger(id,user_id,amount,reason,ref,day)
 VALUES('roulette:stake:'||NEW.id,NEW.user_id,-NEW.stake,'Ruleta · fitxes','roulette:stake:'||NEW.id,NEW.day);
 INSERT INTO ledger(id,user_id,amount,reason,ref,day)
 SELECT 'roulette:prize:'||NEW.id,NEW.user_id,NEW.payout,'Ruleta · premi, número '||NEW.result,'roulette:prize:'||NEW.id,NEW.day WHERE NEW.payout>0;
END;
